#!/usr/bin/env node
// scripts/process-client-showroom-images.mjs
// One-off pipeline for the /client-showroom page.
// Walks images/client-showcase-pool-images/** (client project folders),
// resizes + compresses every photo with sharp, and writes it out under
// public/images/client-showroom/ with a SEQUENTIAL anonymous filename
// (photo-0001.jpg...) — never the source client folder/file name — then
// records the final {src,width,height} list to lib/client-showroom-images.ts
// for the gallery component to render.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SOURCE_DIR = path.join(ROOT, "images", "client-showcase-pool-images");
const OUT_DIR = path.join(ROOT, "public", "images", "client-showroom");
const MANIFEST_PATH = path.join(ROOT, "lib", "client-showroom-images.ts");
const MAX_EDGE = 1600;
const CONCURRENCY = 8;

// Folders that are personal/off-topic candids (people/pets swimming) rather
// than finished-project photography - excluded from the public showroom.
const EXCLUDE_DIRS = new Set(["People Swimming", "Dogs Swimming"]);
// Phone-app UI screenshots, generic stock-photo downloads, and a
// third-party business's own marketing photo - excluded as non-project /
// non-original content.
const EXCLUDE_FILE_PATTERNS = [
  /screenshot.*instagram/i,
  /^images(\s*\(\d+\))?\.(jpe?g|png)$/i,
  /ambiance/i,
  /Photo Jan 29 2025, 11 04 09 AM/i, // Goel - client requested removal
];

function mulberry32(seed) {
  let a = seed;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function seededShuffle(arr, seed) {
  const rand = mulberry32(seed);
  const out = [...arr];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const out = [];
  for (const e of entries) {
    if (e.isDirectory() && EXCLUDE_DIRS.has(e.name)) continue;
    const full = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(full)));
    else out.push(full);
  }
  return out;
}

async function processOne(srcPath, index) {
  const filename = `photo-${String(index + 1).padStart(4, "0")}.jpg`;
  const outPath = path.join(OUT_DIR, filename);
  const image = sharp(srcPath, { failOn: "none" }).rotate();
  const meta = await image.metadata();
  const needsResize = (meta.width ?? 0) > MAX_EDGE || (meta.height ?? 0) > MAX_EDGE;
  const pipeline = needsResize
    ? image.resize({ width: MAX_EDGE, height: MAX_EDGE, fit: "inside", withoutEnlargement: true })
    : image;
  const info = await pipeline
    .flatten({ background: "#ffffff" })
    .jpeg({ quality: 78, mozjpeg: true, progressive: true })
    .toFile(outPath);
  return { src: `/images/client-showroom/${filename}`, width: info.width, height: info.height };
}

async function run() {
  await fs.mkdir(OUT_DIR, { recursive: true });

  const allFiles = (await walk(SOURCE_DIR)).filter(
    (f) =>
      /\.(jpe?g|png)$/i.test(f) &&
      !path.basename(f).startsWith(".") &&
      !EXCLUDE_FILE_PATTERNS.some((re) => re.test(path.basename(f)))
  );

  const shuffled = seededShuffle(allFiles, 20260813);

  console.log(`Found ${shuffled.length} source images. Processing with concurrency ${CONCURRENCY}...`);

  const results = new Array(shuffled.length);
  let cursor = 0;
  let done = 0;

  async function worker() {
    while (cursor < shuffled.length) {
      const i = cursor++;
      try {
        results[i] = await processOne(shuffled[i], i);
      } catch (err) {
        console.error(`Failed: ${shuffled[i]}`, err.message);
      }
      done++;
      if (done % 40 === 0 || done === shuffled.length) {
        console.log(`  ${done}/${shuffled.length}`);
      }
    }
  }

  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  const manifest = results.filter(Boolean);

  const tsContent = `// Auto-generated by scripts/process-client-showroom-images.mjs — do not hand-edit.
// Anonymous, sequentially-named project photos for the /client-showroom page.
export type ShowroomImage = { src: string; width: number; height: number };

export const CLIENT_SHOWROOM_IMAGES: ShowroomImage[] = ${JSON.stringify(manifest, null, 2)};
`;

  await fs.writeFile(MANIFEST_PATH, tsContent);
  console.log(`\nWrote ${manifest.length} images to ${OUT_DIR}`);
  console.log(`Wrote manifest to ${MANIFEST_PATH}`);
}

run();
